const KEYS = ['id', 'name', 'role', 'protein', 'cuisine', 'method', 'minutes', 'seasons', 'ing', 'stepStr'];

export const RECIPES = ROWS.map((row) => {
  const o = {};
  KEYS.forEach((k, i) => { o[k] = row[i]; });
  return {
    id: o.id,
    name: o.name,
    role: o.role,
    protein: o.protein,
    cuisine: o.cuisine,
    method: o.method,
    minutes: o.minutes,
    seasons: o.seasons,
    ingredients: o.ing.map(([id, grams]) => ({ id, grams })),
    steps: o.stepStr.split('｜'),
  };
});

export const RECIPE_BY_ID = new Map(RECIPES.map((r) => [r.id, r]));

export function recipesByRole(role) {
  return RECIPES.filter((r) => r.role === role);
}
